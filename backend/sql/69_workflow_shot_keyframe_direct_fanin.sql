                             "variant_id":"{{__item__.variant_id}}"}}},
        {"id":"extra_refs","type":"action","position":{"x":900,"y":420},
         "config":{"name":"shot.keyframe.extra_references",
                   "args":{"project_id":"{{input.project_id}}","shot_id":"{{input.shot_id}}"},
