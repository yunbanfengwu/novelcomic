                   "ui":{"tap":"text","title":"关键帧定格画面提示词","show":"text","w":420,"h":320}}},
        {"id":"each_element","type":"loop","position":{"x":900,"y":150},
         "config":{"source":"{{elements.items}}","body":["ensure_sheet"],"concurrency":4,
                   "failure_policy":"required_blocks",
                   "ui":{"tap":"loop","title":"要素图片生成","w":420,"h":180}}},
        {"id":"ensure_sheet","type":"subflow","position":{"x":940,"y":520},
         "config":{"slug":"element-sheet","version":1,
                   "inputs":{"project_id":"{{input.project_id}}",
