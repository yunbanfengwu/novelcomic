    description='分析关联要素 → 按要素动态展开设定图 → 所有图片与额外参考直接汇入关键帧生成。',
    input_schema='{"project_id":{"type":"int","required":true},"shot_id":{"type":"int","required":true}}'::jsonb,
    output_schema='{"keyframe_url":{"type":"string"},"reference_images":{"type":"array"}}'::jsonb,
    graph=$g${
      "nodes":[
        {"id":"start","type":"start","position":{"x":40,"y":240},
         "config":{"ui":{"tap":"start","title":"开始"}}},
        {"id":"analyze","type":"action","position":{"x":380,"y":200},
         "config":{"name":"shot.ensure_elements",
                   "args":{"project_id":"{{input.project_id}}","shot_id":"{{input.shot_id}}"},
                   "ui":{"tap":"text","title":"分析分镜关联要素","show":"summary","w":420,"h":300}}},
        {"id":"elements","type":"action","position":{"x":720,"y":520},
         "config":{"name":"shot.elements",
                   "args":{"project_id":"{{input.project_id}}","shot_id":"{{input.shot_id}}"},
                   "ui":{"hide":true}}},
        {"id":"script","type":"action","position":{"x":700,"y":520},
         "config":{"name":"shot.keyframe.script",
                   "args":{"project_id":"{{input.project_id}}","shot_id":"{{input.shot_id}}"},
