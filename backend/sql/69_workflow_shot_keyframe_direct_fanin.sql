        {"id":"gen","type":"gen","position":{"x":1450,"y":210},
         "config":{"modality":"image","node_id":"{{input.shot_id}}",
                   "assemble":{"name":"shot.keyframe.layers",
                     "args":{"project_id":"{{input.project_id}}","shot_id":"{{input.shot_id}}",
