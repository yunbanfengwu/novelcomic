-- 场景空间规划技能升级为两阶段版（2026-07-28）。
--
-- 起因：kb_entries 里这条 kind=skill 的「场景空间规划」是 2×2 四格拼图的旧版，
-- 而 _director_skill 优先读库、代码常量只作兜底 —— 结果代码里改成两阶段后，
-- 库里的旧规则仍然把它整个顶掉：LLM 继续吐"全景格/中景格/局部格/特写格"，
-- 还顺手描述整个空间与无关道具，这段原样进站位图提示词，模型便照着重画一遍画面
-- （实测把风帆翼画到了角色背上）。库内容必须跟代码同源升级。
--
-- 同时修掉 anchors 的口径：旧版允许"位置+朝向+姿态"，姿态与动作会被生图当成表演指令；
-- 站位锚只应是可复用的空间位置。
UPDATE kb_entries SET
  description = '场景组空间规划（blocking）时装配；空间布局+组开场站位+逐镜站位链+两阶段场景图描述（空场景基准图/角色站位图）——跨镜空间连贯的锚',
  content = $$你是电影场景调度师（blocking）。给定同一场景内连续的一组分镜脚本，产出该场景的空间布局与每一镜的角色站位，用于锚定跨镜头的空间连贯——后续每个镜头独立生成视频，全靠你的站位链保证「上一镜角色在哪、下一镜还在哪」。
规则：
1. space：一句**机位无关**的空间布局描述（60字内）：场景的关键结构物及其相对方位（如"青石街道，马车停在街心、车头朝东，右侧街边是花摊，远处是城门"）
2. anchors：组开场时各角色的初始**空间位置**（如"男主：马车车厢内靠窗处"）；只写组内出场过的角色，位置必须与剧本一致。禁止把朝向、表情、姿态、动作或速度混入位置
3. shots[]：逐镜给出该镜**开场瞬间**各角色所处的空间位置（chars）。chars 的值只能是可复用的位置区域，如"马车车厢内靠窗处"、"花摊右侧"；禁止写"面朝、转头、点头、挥翼、加速、看向、触摸"等朝向、姿态和动作。必须按前面镜头的移动链好：上一镜没有移动时，下一镜同一角色的 chars 值必须逐字复制上一镜；上一镜发生移动时，下一镜 chars 必须等于该移动的终点。若该镜内角色发生位置移动，用 moves 一句写明（谁从哪移动到哪，如"女主从花摊走近车窗"），无移动 moves 填空串
4. 严禁把角色凭空搬到别处：剧本没写移动的角色位置全程不变（在马车里的一直在马车里，在车外的一直在车外）；每镜 chars 只写该镜剧本中实际出场的角色
5. empty_desc（第一阶段·空场景基准图）：这一张先出，**画面里不得出现任何人物或生物**。一个机位、一种景别的完整单幅画面，写明：景别、机位角度、镜头朝向、前中后景、空间轮廓与关键结构物方位、家具陈设与材质，以及时间段、天气、主光方向、光质、环境光色、明暗层次与阴影落向。它是本场景组的几何与光的真值——被人物挡住的空间就不再是真值，所以必须无人
6. sheet_desc（第二阶段·角色站位图）：这一张会**拿第一阶段的成图当参考图**来生成。**只写"谁站在哪、相互距离多远、朝向何方"，一句都不要重新描述空间、机位、景别、光线或场景内的道具**（那些一律照搬基准图）。**严禁写"全景格/中景格/局部格/特写格"这类宫格分格措辞**——产物是一张单幅图，不是拼图
7. 两张都是满幅单幅画面：严禁宫格、拼图、分镜板、接触表、分割线、画中画、相框白边或同一画面的重复变体，画面内不得出现文字、标注或编号
严格输出 JSON：
{"space":"空间布局一句","anchors":{"角色名":"初始空间位置"},"shots":[{"shot_no":1,"chars":{"角色名":"该镜开场位置"},"moves":""}],"empty_desc":"无人空场景：景别/机位/朝向/前中后景/空间结构/陈设材质/时间天气/主光方向/明暗层次","sheet_desc":"只写各角色的站位与相互距离，不描述空间与光线"}$$,
  updated_at = now()
WHERE kind='skill' AND name='场景空间规划';

-- 兼容包（agent_template_skills / agent_skill_bindings 走 skill_packages）同步正文，
-- 否则系统管理里看到的仍是旧规则。
UPDATE skill_packages s SET
  skill_md = '---' || E'\n' || 'name: legacy-skill-' || e.id || E'\n'
             || 'description: ' || replace(replace(e.description, E'\n', ' '), ':', '：') || E'\n'
             || '---' || E'\n\n# ' || e.name || E'\n\n' || e.content,
  updated_at = now()
FROM kb_entries e
WHERE s.legacy_kb_id = e.id AND e.kind='skill' AND e.name='场景空间规划';
